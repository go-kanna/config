func TestMain(m *testing.M) {
	// Before any test runs: t.Setenv would rule out t.Parallel. The modules
	// the tests write are outside any workspace.
	if err := os.Setenv("GOWORK", "off"); err != nil {
		panic(err)
	}
	os.Exit(m.Run())
}

// writeModule writes files into a fresh module and returns its directory. The
// module resolves github.com/go-kanna/config to this checkout, which the
// generated code imports, and borrows its go.sum so that nothing is fetched.
func writeModule(t *testing.T, files map[string]string) string {
	t.Helper()

	root, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	sum, err := os.ReadFile(filepath.Join(root, "go.sum")) //nolint:gosec // this checkout's own go.sum
	if err != nil {
		t.Fatal(err)
	}

	dir := t.TempDir()
	files["go.mod"] = "module example.com/app\n\ngo 1.27.0\n\n" +
		"require (\n\tgithub.com/go-kanna/config v0.0.0\n" +
		"\tgithub.com/go-kanna/validator v0.0.28-0.20261110121539-f5b496614d8c\n)\n\n" +
		"replace github.com/go-kanna/config => " + root + "\n"
	files["go.sum"] = string(sum)
	for name, content := range files {
		writeFile(t, filepath.Join(dir, name), content)
	}
	return dir
}

func writeFile(t *testing.T, path, content string) {
	t.Helper()

	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
}

func run(t *testing.T, dir string, args ...string) (int, string) {
	t.Helper()

	var stdout, stderr bytes.Buffer
	code := gen.Command().Exec(cli.Env{Out: &stdout, Err: &stderr, Dir: dir}, args)
	return code, stderr.String()
}

const appSrc = "package app\n\n//kanna:config\ntype API struct {\n\tPort int `default:\"8080\" validate:\"gte=1\"`\n}\n"

func TestCommand_Generates(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{"app.go": appSrc})
	if code, stderr := run(t, dir); code != cli.ExitOK || stderr != "" {
		t.Fatalf("run = %d, stderr %q", code, stderr)
	}
	got, err := os.ReadFile(filepath.Join(dir, "config_gen.go")) //nolint:gosec // the file the run wrote
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"// Code generated by kanna-config. DO NOT EDIT.",
		"func DefineAPIFlags(fs *flag.FlagSet) {",
		"func LoadAPI(src source.Source) (API, error) {",
	} {
		if !strings.Contains(string(got), want) {
			t.Errorf("config_gen.go does not contain %q:\n%s", want, got)
		}
	}
	if code, stderr := run(t, dir, "-check"); code != cli.ExitOK {
		t.Errorf("-check = %d, stderr %q", code, stderr)
	}

	cmd := exec.CommandContext(t.Context(), "go", "vet", "./...")
	cmd.Dir = dir
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Errorf("go vet: %v\n%s", err, out)
	}
}

func TestCommand_DeclaredAlready(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{
		"app.go":  appSrc,
		"load.go": "package app\n\nfunc LoadAPI() {}\n",
	})
	code, stderr := run(t, dir)
	want := "./load.go:3:6: error: LoadAPI is declared already, which kanna-config writes for API\n" +
		"  rename it, or remove the //kanna:config on API\n"
	if code != cli.ExitFailure || stderr != want {
		t.Errorf("run = %d, stderr:\n%s\nwant:\n%s", code, stderr, want)
	}
}

func TestCommand_Misplaced(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{"app.go": "package app\n\n" +
		"//kanna:config\ntype Level string\n\n" +
		"//kanna:config\ntype Alias = struct{ Port int }\n\n" +
		"//kanna:config\ntype Source interface{ Port() int }\n\n" +
		"//kanna:config\nfunc Load() {}\n\n" +
		"//kanna:config\nvar Port int\n"})
	code, stderr := run(t, dir)
	want := "./app.go:3:1: error: //kanna:config marks a struct type, not a type other than a struct or an interface, " +
		"so nothing reads it\n" +
		"  write it right above a struct type\n" +
		"./app.go:6:1: error: //kanna:config marks a struct type, not a type alias, so nothing reads it\n" +
		"  write it right above a struct type\n" +
		"./app.go:9:1: error: //kanna:config marks a struct type, not an interface type, so nothing reads it\n" +
		"  write it right above a struct type\n" +
		"./app.go:12:1: error: //kanna:config marks a struct type, not a function, so nothing reads it\n" +
		"  write it right above a struct type\n" +
		"./app.go:15:1: error: //kanna:config marks a struct type, not a variable, so nothing reads it\n" +
		"  write it right above a struct type\n"
	if code != cli.ExitFailure || stderr != want {
		t.Errorf("run = %d, stderr:\n%s\nwant:\n%s", code, stderr, want)
	}
}

func TestCommand_RemovesWhatIsGone(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{"app.go": appSrc})
	if code, stderr := run(t, dir); code != cli.ExitOK {
		t.Fatalf("run = %d, stderr %q", code, stderr)
	}
	writeFile(t, filepath.Join(dir, "app.go"), "package app\n\ntype API struct{ Port int }\n")
	code, stderr := run(t, dir)
	if code != cli.ExitOK || !strings.Contains(stderr, "no struct is marked //kanna:config") {
		t.Errorf("run = %d, stderr %q", code, stderr)
	}
	if _, err := os.Stat(filepath.Join(dir, "config_gen.go")); !os.IsNotExist(err) {
		t.Errorf("config_gen.go is still there: %v", err)
	}
}

func TestCommand_Deps(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{"app.go": appSrc})
	var stdout, stderr bytes.Buffer
	if code := gen.Command().Exec(cli.Env{Out: &stdout, Err: &stderr, Dir: dir}, []string{"-deps"}); code != cli.ExitOK {
		t.Fatalf("-deps = %d, stderr %q", code, stderr.String())
	}
	for _, want := range []string{`"example.com/app.LoadAPI"`, `"example.com/app.DefineAPIFlags"`, "config_gen.go"} {
		if !strings.Contains(stdout.String(), want) {
			t.Errorf("-deps does not report %s:\n%s", want, stdout.String())
		}
	}
}
